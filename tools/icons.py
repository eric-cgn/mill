def frame(i):
    return SAILS[i].strip('\n') + '\n' + TOWER.strip('\n')


def bar_frame(i):
    '''The toolbar's windmill, 14 rows to fit the 14-row toolbar: a frame without its
    blank top row, and with one of the tower's two matching rows'''
    r = rows(frame(i))
    assert '#' not in r[0] and r[11] == r[12]
    return '\n'.join(r[1:12] + r[13:])


def fill_mask(art):
    '''The Finder mask: the icon grown by one pixel all round.'''
    g = rows(art)
    h, w = len(g), len(g[0])
    near = lambda x, y: any(0 <= x + dx < w and 0 <= y + dy < h and g[y + dy][x + dx] == '#'
                            for dx in (-1, 0, 1) for dy in (-1, 0, 1))
    return '\n'.join(''.join('#' if near(x, y) else '.' for x in range(w)) for y in range(h))


def silhouette(art):
    '''The Finder mask for a large icon: grown by a pixel, with every enclosed space filled.'''
    grown = rows(fill_mask(art))
    h, w = len(grown), len(grown[0])
    outside, stack = set(), [(x, y) for x in range(w) for y in (0, h - 1)] + [(x, y) for y in range(h) for x in (0, w - 1)]
    while stack:
        x, y = stack.pop()
        if (x, y) in outside or not (0 <= x < w and 0 <= y < h) or grown[y][x] == '#': continue
        outside.add((x, y))
        stack += [(x + 1, y), (x - 1, y), (x, y + 1), (x, y - 1)]
    return '\n'.join(''.join('.' if (x, y) in outside else '#' for x in range(w)) for y in range(h))


def gif(art, mask):
    '''A GIF89a of an icon: black and white inside its mask, transparent outside.
    The LZW stream is all literals, with a clear code every two so codes stay 3 bits.'''
    g, m = rows(art), rows(mask)
    h, w = len(g), len(g[0])
    pixels = [(1 if g[y][x] == '#' else 0) if m[y][x] == '#' else 2 for y in range(h) for x in range(w)]
    codes = []
    for i in range(0, len(pixels), 2):
        codes += [4] + pixels[i:i + 2]      # clear, then two literals
    codes.append(5)                         # end of information
    bits = acc = 0
    data = bytearray()
    for c in codes:
        acc |= c << bits
        bits += 3
        while bits >= 8:
            data.append(acc & 0xFF)
            acc >>= 8
            bits -= 8
    if bits:
        data.append(acc)
    blocks = b''.join(bytes([len(data[i:i + 255])]) + data[i:i + 255] for i in range(0, len(data), 255))
    return (b'GIF89a' + struct.pack('<HHBBB', w, h, 0x81, 0, 0) +
            bytes([255, 255, 255, 0, 0, 0, 255, 255, 255, 255, 255, 255]) +   # white, black, (transparent), unused
            b'\x21\xf9\x04\x01\x00\x00\x02\x00' +                       # index 2 is transparent
            b'\x2c' + struct.pack('<HHHHB', 0, 0, w, h, 0) + b'\x02' + blocks + b'\x00\x3b')


def c_array(name, art):
    ws = words(art)
    body = ', '.join('0x%04X' % v for v in ws)
    return 'static const unsigned short %s[%d] = { %s };' % (name, len(ws), body)


