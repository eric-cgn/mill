def rows(art):
    return [line for line in art.strip('\n').split('\n')]


def mirror(art):
    return '\n'.join(r[::-1] for r in rows(art))


def words(art, width=16):
    '''Each row as a 16-bit word, left-aligned (QuickDraw bit order).'''
    out = []
    for r in rows(art):
        v = 0
        for i, ch in enumerate(r.ljust(width, '.')[:width]):
            if ch == '#': v |= 1 << (width - 1 - i)
        out.append(v)
    return out


