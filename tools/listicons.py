def rows(art):
    r = [l for l in art.strip('\n').split('\n')]
    assert len(r) == 16 and all(len(l) == 16 for l in r), r
    return r

def mask(r):
    out = [[True] * 16 for _ in range(16)]
    stack = [(y, x) for y in range(16) for x in range(16) if y in (0, 15) or x in (0, 15)]
    while stack:
        y, x = stack.pop()
        if not (0 <= y < 16 and 0 <= x < 16) or not out[y][x] or r[y][x] == '#':
            continue
        out[y][x] = False
        stack += [(y + 1, x), (y - 1, x), (y, x + 1), (y, x - 1)]
    return out

def words(bits):
    return ['%04X' % int(''.join('1' if b else '0' for b in row), 2) for row in bits]

with open(OUT, 'w') as f:
    f.write('/* Generated by tools/listicons.py; edit there. Mill\'s shared listing icons, 64 to 79\n'
            '   (kMillIcon... in sdk/Interfaces/MillPlugIn.h): a picture, then its mask. */\n')
    for rid, name, art in ICONS:
        r = rows(art)
        pic = [[c == '#' for c in row] for row in r]
        f.write("data 'ics#' (%d, \"%s\") {\n" % (rid, name))
        w = words(pic) + words(mask(r))
        for i in range(0, 32, 8):
            f.write('\t$"%s"\n' % ' '.join(w[i:i + 8]))
        f.write('};\n')
