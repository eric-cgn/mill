#!/usr/bin/env python3
"""The installer's payload: build/installer/payload.r, a Rez file of gzip-compressed MacBinary files
as 'MBIN' resources named for where each goes ("Mill", "Mill Plug-Ins:Web Fonts", "Mill Plug-In
SDK:Read Me"). Needs what ./build.sh and ./build.sh disk make. ./build.sh installer runs it."""
import gzip, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import disk, kit

root = kit.root
out = os.path.join(root, 'build', 'installer')


def rez_string(s):
    return '"' + ''.join(c if 32 <= ord(c) < 127 and c not in '"\\' else '\\$%02X' % s.encode('mac_roman')[i]
                         for i, c in enumerate(s)) + '"'


def main():
    os.makedirs(os.path.join(out, 'payload'), exist_ok=True)
    mill = disk.need(os.path.join(root, 'build', 'Mill.bin'), './build.sh')
    fonts = disk.need(os.path.join(root, 'build', 'fonts', 'Web Fonts.bin'), './build.sh disk')
    inet = disk.need(os.path.join(root, 'plugins', 'internet', 'build', 'Internet Services.bin'), './build.sh disk')
    bundled = os.path.join(out, 'Mill.bin')
    disk.with_bundle_bit(mill, bundled)
    items = [(128, 'Mill', open(bundled, 'rb').read()),
             (129, 'Mill Plug-Ins:Internet Services', open(inet, 'rb').read()),
             (130, 'Mill Plug-Ins:Web Fonts', open(fonts, 'rb').read())]
    for i, (parts, name, mb) in enumerate(kit.entries()):
        items.append((1000 + i, ':'.join(['Mill Plug-In SDK'] + parts + [name]), mb))
    r = ['/* Generated by tools/installer.py */']
    total = 0
    for rid, name, mb in items:
        z = gzip.compress(mb, 9, mtime=0)
        total += len(z)
        path = os.path.join(out, 'payload', '%d.gz' % rid)
        open(path, 'wb').write(z)
        r.append("data 'MBIN' (%d, %s) { $$read(%s) };" % (rid, rez_string(name), rez_string(path)))
    open(os.path.join(out, 'payload.r'), 'w').write('\n'.join(r) + '\n')
    print('%d files, %d bytes compressed' % (len(items), total))


if __name__ == '__main__':
    main()
