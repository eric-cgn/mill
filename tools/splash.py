#!/usr/bin/env python3
'''Makes the splash screen's picture (src/splash.r) from art/quixote.jpg: scaled to
SPLASH_W pixels wide with macOS's sips, then dithered with Atkinson's dither like
Mill's own pictures. Run on a Mac after changing the art: python3 tools/splash.py'''

import os
import struct
import subprocess
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
ART = os.path.join(HERE, '..', 'art', 'quixote.jpg')
OUT = os.path.join(HERE, '..', 'src', 'splash.r')
SPLASH_W = 192


def gray_bmp(path):
    b = open(path, 'rb').read()
    off = struct.unpack('<I', b[10:14])[0]
    w, h = struct.unpack('<ii', b[18:26])
    n = struct.unpack('<H', b[28:30])[0] // 8
    row = (w * n + 3) // 4 * 4
    up, h = h > 0, abs(h)
    rows = []
    for y in range(h):
        r = b[off + (h - 1 - y if up else y) * row:][:row]
        rows.append([(r[x * n + 2] * 77 + r[x * n + 1] * 151 + r[x * n] * 28) >> 8 for x in range(w)])
    return w, h, rows


def atkinson(w, h, g):
    err = [[0] * (w + 3) for _ in range(h + 2)]
    out = [[0] * w for _ in range(h)]
    for y in range(h):
        for x in range(w):
            v = g[y][x] + err[y][x + 1]
            e = v if v < 128 else v - 255
            out[y][x] = 1 if v < 128 else 0
            e //= 8
            for dx, dy in ((1, 0), (2, 0), (-1, 1), (0, 1), (1, 1), (0, 2)):
                err[y + dy][x + 1 + dx] += e
    return out


def main():
    with tempfile.TemporaryDirectory() as tmp:
        bmp = os.path.join(tmp, 'small.bmp')
        subprocess.run(['sips', '-s', 'format', 'bmp', '--resampleWidth', str(SPLASH_W), ART, '--out', bmp],
                       check=True, stdout=subprocess.DEVNULL)
        w, h, g = gray_bmp(bmp)
    bits = atkinson(w, h, g)
    row_bytes = (w + 15) // 16 * 2
    data = struct.pack('>hhh', w, h, row_bytes)
    for r in bits:
        line = bytearray(row_bytes)
        for x, v in enumerate(r):
            if v: line[x >> 3] |= 0x80 >> (x & 7)
        data += bytes(line)
    with open(OUT, 'w') as f:
        f.write('/* Generated by tools/splash.py from art/quixote.jpg (G. A. Harker, 1910); edit there. */\n')
        f.write("/* width, height, row bytes, then 1-bit rows (1 = black) */\n")
        f.write("data 'SPLS' (128, \"Splash\") {\n")
        for i in range(0, len(data), 32):
            f.write('\t$"%s"\n' % data[i:i + 32].hex().upper())
        f.write('};\n')
    print('%dx%d, %d bytes' % (w, h, len(data)))


if __name__ == '__main__':
    main()
